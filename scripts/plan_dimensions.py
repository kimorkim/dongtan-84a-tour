def interpolate(value, table):
    i=max(0,min(len(table)-2,bisect_right([p[0] for p in table],value)-1))
    a,b=table[i],table[i+1]
    return a[1]+(value-a[0])*(b[1]-a[1])/(b[0]-a[0])

def point(x,y):
    # Distinct north/south faces that happened to share a traced coordinate.
    nx=interpolate(x,X_MAP)
    ny=interpolate(y,Y_MAP)
    if y>=8.175 and 8.194<=x<=8.7:
        nx=interpolate(x,[(8.194,8.080),(8.662,8.550),(8.7,8.550)])
    if y<7.8 and 7.987<x<8.925:
        nx=interpolate(x,[(7.987,7.875),(8.925,8.805)])
    if x>4.3 and y<4.2:
        ny=interpolate(y,[(0,.08),(.506,.600),(.825,.800),(.844,.800),(.85,.920),(4.237,4.330)])
    if 5.58<y<5.72 and x<5.2:
        ny=interpolate(y,[(5.58,5.700),(5.625,5.750),(5.644,5.750),(5.85,5.970),(5.869,5.970)])
    if 7.52<y<8.10:
        if x<7.7:
            ny=interpolate(y,[(7.537,7.660),(7.65,7.775),(8.044,8.170),(8.062,8.170),(8.175,8.260)])
        elif x>=10.55:
            ny=interpolate(y,[(7.537,7.660),(7.65,7.660),(7.969,7.895),(8.10,8.025)])
        elif x>=7.7:
            ny=interpolate(y,[(7.537,7.735),(7.65,7.850),(7.931,8.120),(7.95,8.120),(8.175,8.360)])
    if y>5.5 and x<4.3 and x>4.10:
        nx+=.010
    if y>5.5 and x>14.6:
        nx-=.020
    return nx,ny

def solid_point(x,y):
    nx,ny=point(x,y)
    return round(nx/.005)*.005,round(ny/.005)*.005

